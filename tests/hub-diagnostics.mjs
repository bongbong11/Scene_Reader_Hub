import assert from 'node:assert/strict';
import {wholeDiagnosticReport} from '../src/debug/whole-report.js';
import {appearanceRollText} from '../src/ui/appearance-status.js';
const paused={judgedAt:'2025-01-01T12:00:00.000Z',model:'jev-latest',sceneIntimacy:{route:'paused',level:4,phase:'active'},details:{},decisions:{},payload:'synthetic private guide'};
const before=JSON.stringify(paused);
const report=wholeDiagnosticReport({judgment:paused});
assert.equal(report.scene.route,'paused');
assert.equal(report.scene.level,4);
assert.equal(report.scene.hasError,false);
assert.deepEqual(report.decisions,{});
assert.equal(JSON.stringify(paused),before,'reading a report does not change saved data');
assert.equal(wholeDiagnosticReport({judgment:{...paused,sceneIntimacy:{...paused.sceneIntimacy,error:'synthetic gate timeout'}}}).scene.hasError,true);
const ordinary=wholeDiagnosticReport({judgment:{sceneIntimacy:{route:'normal',level:0,phase:'ended'},rawChoices:{event_route:{choice:'continue',confidence:0.43}},details:{event_route:{selected:'continue',certainty:0.43,effective:'none',policyEffective:'none',threshold:0.56/1.3,fallbackApplied:true}},payload:'ready',worldPayload:'world'}});
assert.equal(ordinary.scene.route,'normal');
assert.equal(ordinary.decisions.event_route.threshold,0.56/1.3);
assert.equal(ordinary.decisions.event_route.fallbackApplied,true);
assert.equal(ordinary.jevOriginalChoices.event_route.choice,'continue');
assert.equal(ordinary.injection.delivery,'see_injection_consume_events','saved payload cannot prove delivery');
assert.equal('payload' in ordinary,false);
assert.equal(JSON.stringify(report).includes('synthetic private guide'),false);
assert.deepEqual(Object.keys(wholeDiagnosticReport({judgment:{details:{'unsafe key':{},safe_key:{}}}}).decisions),['safe_key']);
assert.equal(wholeDiagnosticReport({}).status,'no_judgment');
assert.equal(wholeDiagnosticReport({judgment:{}}).scene,null);
assert.match(appearanceRollText({passed:true,roll:27,chance:50}),/통과했지만/);
assert.doesNotMatch(appearanceRollText({passed:true}),/통과하지 않아/);
assert.match(appearanceRollText({passed:false}),/통과하지 않아/);
console.log('Hub diagnostics passed: paused/failed/normal distinction, acceptance thresholds, immutable private reports, delivery limits and passed-but-unused appearance display.');
