import assert from 'node:assert/strict';
import {buildTurnReport} from '../src/debug/turn-report.js';
import {appearanceRollText} from '../src/ui/appearance-status.js';
const paused={judgedAt:'2026-10-02T14:10:28.820Z',model:'jev-latest',sceneIntimacy:{route:'paused',level:4,phase:'active'},details:{},decisions:{},payload:'fixed guide'};
const before=JSON.stringify(paused);
const report=buildTurnReport({judgment:paused});
assert.equal(report.mode,'scene_paused');
assert.equal(report.generalJudgment,'skipped_for_scene');
assert.equal(report.sceneIntimacy.level,4);
assert.deepEqual(report.decisions,{});
assert.equal(JSON.stringify(paused),before,'reading a report does not change saved data');
assert.equal(buildTurnReport({judgment:{...paused,sceneIntimacy:{...paused.sceneIntimacy,error:'gate timeout'}}}).mode,'scene_pause_retained_after_error');
const ordinary=buildTurnReport({judgment:{sceneIntimacy:{route:'normal',level:0,phase:'ended'},jevDiagnostics:{requested:85,valid:85},rawChoices:{event_route:{choice:'continue',confidence:0.43}},details:{event_route:{selected:'continue',certainty:0.43,effective:'none',policyEffective:'none',threshold:0.56/1.3,fallbackApplied:true}},payload:'ready',worldPayload:'world'}});
assert.equal(ordinary.mode,'normal_judgment');
assert.equal(ordinary.generalJudgment,'completed');
assert.equal(ordinary.decisions.event_route.threshold,0.56/1.3);
assert.match(ordinary.decisions.event_route.reason,/확신도/);
assert.equal(ordinary.injection.delivery,'not_verified_by_this_report','saved payload cannot prove delivery');
assert.equal('payload' in ordinary,false);
assert.deepEqual(buildTurnReport({judgment:{...paused,rawChoices:{keep:{},omit:{}},details:{keep:{},omit:{}}},related:key=>key==='keep'}).jevOriginalChoices,{keep:{}});
assert.equal(buildTurnReport({judgment:{}}).mode,'unknown_legacy');
assert.match(appearanceRollText({passed:true,roll:27,chance:50}),/통과했지만/);
assert.doesNotMatch(appearanceRollText({passed:true}),/통과하지 않아/);
assert.match(appearanceRollText({passed:false}),/통과하지 않아/);
console.log('Hub diagnostics passed: paused/failed/normal distinction, acceptance thresholds, filtered immutable reports, delivery limits and passed-but-unused appearance display.');
