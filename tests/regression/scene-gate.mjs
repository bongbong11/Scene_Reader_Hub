import assert from 'node:assert/strict';
import {sceneGateRequest,resolveSceneGate} from '../../src/scene/intimacy-gate.js';
import {buildPausedInjection} from '../../prompt-library.js';

const request=sceneGateRequest({model:'jev',transcript:'[1] USER: A kiss.\n[2] CHARACTER: They begin explicit sexual activity.',people:[{id:'wade',name:'Wade'}]});
assert.ok(Object.hasOwn(request.questions.scene_evidence.criteria,'2'));
const judge=(status,evidence,previous='normal')=>resolveSceneGate({scene_status:{choice:status},scene_evidence:{choice:evidence},scene_participant_0:{choice:'direct'}},request,previous);
assert.ok(request.questions.scene_status);assert.equal(request.questions.scene_level,undefined);assert.equal(request.questions.scene_phase,undefined);
assert.equal(judge('affection','1').route,'normal','kissing does not pause the route');
assert.equal(judge('explicit_begin','none').route,'normal','a transition needs supplied RP evidence');
assert.equal(judge('explicit_begin','99').route,'normal','fabricated source is rejected');
assert.equal(judge('explicit_begin','2').transition,'entered');
assert.equal(judge('unknown','none','paused').route,'paused','missing classification preserves current state');
assert.equal(judge('brief_pause','2','paused').route,'paused');
assert.equal(judge('ended','2','paused').transition,'exited');
assert.equal(judge('ordinary','1','paused').transition,'exited','any applicable supplied visible source can establish the current classification');
assert.equal(judge('explicit_ongoing','2','paused').route,'paused');
assert.equal(judge('invalid','2','paused').route,'paused');
assert.equal(judge('ended','none','paused').confirmation,'unresolved');
const prompt=buildPausedInjection({settings:{},referenceLines:['<CHARACTER_REFERENCE>Stored reference.</CHARACTER_REFERENCE>']});
assert.match(prompt,/Stored reference/);
assert.match(prompt,/NSFW, and character-specific kink instructions/);
assert.ok(!prompt.includes('CHARACTER_EXECUTION'));
console.log('Scene gate transitions and paused injection passed.');
