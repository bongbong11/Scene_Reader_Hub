import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
const check = process.argv.includes('--check');
const sourceArg = process.argv.slice(2).find(arg => arg !== '--check');
if (!sourceArg) throw new Error('Usage: node scripts/sync-character-core.mjs <Character_Reasoner checkout> [--check]');
const source = path.resolve(sourceArg);
const target = path.resolve(import.meta.dirname, '../src/vendor/character-reasoner');
const bytes = await readFile(path.join(source, 'core/index.js'));
const sha256 = createHash('sha256').update(bytes).digest('hex');
const versionModule = `// Generated by sync-character-core.mjs.\nexport const CORE_SHA256 = '${sha256}';\n`;
if (check) {
    const actual = await readFile(path.join(target, 'index.js'));
    const lock = JSON.parse(await readFile(path.join(target, 'sync.json'), 'utf8'));
    if (!actual.equals(bytes) || lock.sha256 !== sha256 || await readFile(path.join(target, 'version.js'), 'utf8') !== versionModule) throw new Error('Character Reasoner core drift: sync from the canonical checkout.');
    console.log('Canonical core and vendored core match exactly.');
} else {
    const gitArgs = ['-c', `safe.directory=${source}`, '-C', source];
    const sourceCommit = execFileSync('git', [...gitArgs, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim();
    let sourceDirty = true;
    try { sourceDirty = !execFileSync('git', [...gitArgs, 'show', `${sourceCommit}:core/index.js`], {stdio:['ignore','pipe','pipe']}).equals(bytes); } catch { /* Uncommitted extraction has no canonical blob yet. */ }
    await mkdir(target, {recursive:true});
    await writeFile(path.join(target, 'index.js'), bytes);
    await writeFile(path.join(target, 'version.js'), versionModule);
    await writeFile(path.join(target, 'sync.json'), JSON.stringify({repository:'https://github.com/bongbong11/Character_Reasoner', sourceCommit, sourceDirty, file:'core/index.js', sha256}, null, 2)+'\n');
    const provenancePath=path.resolve(import.meta.dirname,'./provenance.json');
    const provenance=JSON.parse(await readFile(provenancePath,'utf8'));
    provenance.characterCommit=sourceCommit;
    await writeFile(provenancePath,JSON.stringify(provenance,null,2)+'\n');
    console.log('Vendored core synchronized. Runtime has no Character Reasoner installation dependency.');
}
